"""答案评审层（档 1：零成本规则，不额外调用 LLM）。

为什么需要它？
真实使用感受是「**它自以为地输出了一个自认合理的结果**」。最典型的一幕是 RAG 答
「资料中未涉及。」——这句话**本身没错**（提示词就是这么要求的），但它说明
**系统其实没答上**，却和正常回答一样被展示出来，用户看不到任何引导。

项目原有的 Critic（`nl2sql/graph.py`）覆盖不到这里，三个原因叠在一起：
1. 它挂在 `execute` 之后，**只审 SQL**；而 RAG 分支在引擎里早返回，压根不在图里；
2. 它**默认关**（`critique_llm=False`，作者的理由是"避免每次查询都双倍成本"）；
3. Streamlit 档用的是 `Text2SQLPipeline` 手写编排，**图根本没跑**。

所以评审放在**引擎出口**（`GRGQueryEngine.ask`）——一处覆盖三个入口
（Streamlit / FastAPI / MCP）与两条编排（pipeline / graph）。

本档只做零成本规则。后续档位接在同一层后面即可：
- 档 2：检索相关度阈值（需 `DocHit` 暴露精排分 + 在线校准阈值）；
- 档 3：LLM 复核（每次问答多一次模型调用，默认关，可配）。
"""
from __future__ import annotations

# ---------------------------------------------------------------------------
# 「资料不足」的兜底话术
# ---------------------------------------------------------------------------
# 提示词要求 LLM 在资料答不上来时就直接说这句话；评审层据此判定
# "这条 RAG 答案其实没答上"。**提示词与检测共用同一常量**，避免两处各写一份而漂移
# （这属于"契约"，不是去猜模型的措辞）。
NO_ANSWER_MARK = "资料中未涉及"

# 引导用的示范问法：让用户知道"这个系统能听懂什么"。
# 刻意覆盖三种能力——指标取值 / 计数 / 排名，都是语义层能解析的问法。
EXAMPLE_QUESTIONS = (
    "各业务线的检测准时率是多少",
    "华东区上个月出具了多少份报告",
    "设备利用率最高的实验室是哪个",
)


def guidance(reason: str) -> str:
    """统一的「引导型」文案：说清为什么答不了 + 给出能用的问法。

    比一句"我不懂"有用得多——用户看到示例才知道该怎么问。
    """
    examples = "\n".join(f"- {q}" for q in EXAMPLE_QUESTIONS)
    return f"{reason}\n\n可以这样问：\n{examples}"


def review_answer(out: dict) -> dict:
    """对最终答案做一次零成本评审；判定"没答上"时把答案降级为引导。

    **保持 `type` 不变**：类型描述的是"走通了哪条路"，不是"结论对不对"——
    这与结构化分支的处理一致（执行成功但 0 行时仍是 `type=result` + `empty=True`，
    由界面给出警示，而不是改类型）。因此调用方与评估集都不受影响，
    只是 `answer` 换成了引导，并多出一个 `review` 字段便于区分。
    """
    if out.get("type") != "rag":
        return out

    answer = out.get("answer") or ""
    if NO_ANSWER_MARK not in answer:
        return out

    return {
        **out,
        "answer": guidance("知识库里没有能回答这个问题的资料。"),
        "review": {
            "verdict": "no_answer",
            "reason": f"RAG 回答命中兜底话术「{NO_ANSWER_MARK}」——说明资料不足以回答该问题",
        },
    }
